#!/bin/bash

# Init
for i in "0x02 0xfe" "0x03 0x0f" "0x06 0xfe" "0x07 0x0f"; do
	i2cset -y 5 0x21 $i
done

# LEDs
for i in 0x00 0x10 0x20 0x40 0x80 0x00; do
	i2cset -y 5 0x21 0x03 $i
	sleep 1
done

# Buzzer
for i in 0x01 0x00 0x01 0x00 0x01 0x00; do
	i2cset -y 5 0x21 0x02 $i
	sleep 0.25
done

# DIP switch
while true; do 
	echo -n PCA9555: GPIO_P1=
	i2cget -y 5 0x21 0x01
	sleep 0.25
done

